import { expect, test } from '@playwright/test';
import { chooseSetting, demoFixture, visible } from './demo-fixture';

// Real offline WebKit pages; singleton routing/native ownership still needs native acceptance.
test('project provenance and global defaults reconcile across independent Settings and project pages', async ({ page }) => {
  const fixture = await demoFixture(page);
  try {
    const prompt = page.locator(visible('prompt')); await prompt.fill('Keep my draft');
    const starts = fixture.calls.filter(call => call.command === 'start_pi').length;
    await page.locator('#open-settings').click();
    await expect(page.locator('#settings-title')).toContainText('Project settings');
    await expect(page.locator('#settings-category-notifications')).toBeHidden();
    await expect(page.locator('#settings-category-keybindings')).toBeHidden();
    await expect(page.locator('#settings-translucency')).toBeHidden();
    await expect(page.locator('#settings-zoom')).toBeHidden();
    await expect(page.locator('#settings-send-auto-follow')).toBeHidden();
    await expect(page.locator('.settings-source')).toHaveCount(2);
    await expect(page.locator('#theme-picker-source')).toHaveText('Inherited');
    await page.locator('#theme-picker').click();
    await page.locator('#palette-list [data-key="dracula"]').click();
    await expect(page.locator('#command-palette')).not.toBeVisible();
    await expect(page.locator('#settings-page')).toBeVisible();
    await expect(page.locator('#theme-picker-source')).toHaveText('Project override');
    expect(fixture.calls.filter(call => call.command === 'preferences_settings')).toHaveLength(0);
    const settingsPage = await fixture.settingsWindow();
    await expect(settingsPage.locator('#settings-title')).toHaveText('Settings');
    await expect(settingsPage.locator('#workspace-layout')).toBeHidden();
    await expect(settingsPage.locator('#settings-zoom')).toBeVisible();
    await expect(settingsPage.locator('#settings-send-auto-follow')).toBeVisible();
    await chooseSetting(settingsPage, 'zoom-level', '150');
    await expect(page.locator('#zoom-level')).toHaveAttribute('value', '150');
    await chooseSetting(settingsPage, 'send-auto-follow', 'never');
    await expect(page.locator('#send-auto-follow')).toHaveAttribute('value', 'never');
    await expect(settingsPage.locator('#theme-picker')).toHaveAttribute('data-theme', 'nimrod');
    await expect(settingsPage.locator('.settings-project-overrides, .settings-project-links')).toHaveCount(0);
    await expect(settingsPage.locator('#settings-scope-description')).toContainText('Project overrides take precedence.');
    await settingsPage.locator('#theme-picker').click();
    await settingsPage.locator('#palette-list [data-key="tokyo-night"]').click();
    await expect(settingsPage.locator('#command-palette')).not.toBeVisible();
    await expect(settingsPage.locator('#settings-page')).toBeVisible();
    await expect(page.locator('#theme-picker')).toHaveAttribute('data-theme', 'dracula');
    await page.bringToFront();
    await page.getByRole('button', { name: 'Remove override for Color theme', exact: true }).click();
    await expect(page.locator('#theme-picker')).toHaveAttribute('data-theme', 'tokyo-night');
    await expect(page.locator('#theme-picker-source')).toHaveText('Inherited');
    await expect(settingsPage.locator('.settings-project-overrides, .settings-project-links')).toHaveCount(0);
    await fixture.editPreferences('{"appearance.theme":"osaka-jade"}');
    await expect(page.locator('#theme-picker')).toHaveAttribute('data-theme', 'osaka-jade');
    await settingsPage.locator('#settings-category-interaction').click();
    await chooseSetting(settingsPage, 'autocomplete-accept', 'tabOrEnter');
    await page.locator('#settings-category-interaction').click();
    await expect(page.locator('#autocomplete-accept')).toHaveAttribute('value', 'tabOrEnter');
    await expect(page.locator('#autocomplete-accept-source')).toHaveText('Inherited');
    await chooseSetting(page, 'autocomplete-accept', 'tabOrEnter');
    await expect(page.locator('#autocomplete-accept-source')).toHaveText('Project override');
    await chooseSetting(settingsPage, 'autocomplete-accept', 'tab');
    await expect(page.locator('#autocomplete-accept')).toHaveAttribute('value', 'tabOrEnter');
    await page.getByRole('button', { name: 'Remove override for Accept autocomplete with', exact: true }).click();
    await expect(page.locator('#autocomplete-accept')).toHaveAttribute('value', 'tab');
    await expect(page.locator('#autocomplete-accept-source')).toHaveText('Inherited');
    await page.locator('#settings-category-runtime').click();
    await settingsPage.locator('#settings-category-runtime').click();
    await settingsPage.locator('#pi-path').fill('/global/pi');
    await settingsPage.locator('#pi-path').press('Enter');
    await expect(page.locator('#pi-path')).toHaveValue('');
    await expect(page.locator('#pi-path')).toHaveAttribute('placeholder', '/global/pi');
    await page.locator('#pi-path').fill('/project/pi');
    await page.locator('#pi-path').press('Enter');
    await expect(page.locator('#pi-path')).toHaveValue('/project/pi');
    await settingsPage.locator('#pi-path').fill('/changed/global/pi');
    await settingsPage.locator('#pi-path').press('Enter');
    await expect(page.locator('#pi-path')).toHaveValue('/project/pi');
    await expect(page.locator('#pi-path')).toHaveAttribute('placeholder', '/changed/global/pi');
    await page.locator('#pi-path').fill('');
    await page.locator('#node-path').click();
    await expect(page.locator('#pi-path')).toHaveValue('');
    await expect(page.locator('#pi-path')).toHaveAttribute('placeholder', '/changed/global/pi');
    await expect(page.locator('.settings-source')).toHaveCount(2);
    await page.locator('#settings-back').click();
    await expect(prompt).toHaveValue('Keep my draft');
    expect(fixture.calls.filter(call => call.command === 'start_pi')).toHaveLength(starts);
    expect(fixture.calls.filter(call => call.command === 'list_project_overrides' || call.command === 'open_owned_project_settings')).toHaveLength(0);
    expect(fixture.errors).toEqual([]);
  } finally { await fixture.close(); }
});
